"""Emit the graph-specific constant tables for rtl/qsx_uf_core.sv.

    python rtl/gen_graph.py --graph build/graphs/d5_q5.qsxg --out build/rtl/d5_q5

writes ``qsx_graph_defs.svh`` (scalar macros, included at file scope) and
``qsx_graph_tables.svh`` (localparam tables, included inside modules). Field i of every packed table
occupies bits [i*W +: W].
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from sim.qsx_graph import Graph  # noqa: E402


def clog2(x: int) -> int:
    return max(1, math.ceil(math.log2(x))) if x > 1 else 1


def pack(vals: list[int], w: int) -> str:
    n = 0
    for i, v in enumerate(vals):
        assert 0 <= v < (1 << w), (v, w)
        n |= v << (i * w)
    return f"{len(vals) * w}'h{n:x}"


def emit(g: Graph, outdir: Path, tb: int | None = None) -> dict:
    V, E = g.V, g.E
    slots: list[list[int]] = [[] for _ in range(V)]
    bedge = [-1] * V
    for e, (u, v) in enumerate(zip(g.eu, g.ev)):
        if v == V:
            bedge[u] = e
        else:
            slots[u].append(e)
            slots[v].append(e)
    md = max(len(s) for s in slots)
    vb = clog2(V + 1)
    eb = clog2(E)
    sb = clog2(md)
    db = clog2(V + 2)
    tb = tb or max(2, clog2(max(g.thr) + 1))
    slot_valid, slot_e, slot_w, slot_back = [], [], [], []
    eu_slot, ev_slot = [0] * E, [0] * E
    for v in range(V):
        for k in range(md):
            if k < len(slots[v]):
                e = slots[v][k]
                w = g.ev[e] if g.eu[e] == v else g.eu[e]
                slot_valid.append(1)
                slot_e.append(e)
                slot_w.append(w)
                if g.eu[e] == v:
                    eu_slot[e] = k
                else:
                    ev_slot[e] = k
            else:
                slot_valid.append(0)
                slot_e.append(0)
                slot_w.append(0)
    for v in range(V):
        for k in range(md):
            if k < len(slots[v]):
                e = slots[v][k]
                w = slot_w[v * md + k]
                slot_back.append(slots[w].index(e))
            else:
                slot_back.append(0)
    obs0 = [o & 1 for o in g.obs]
    outdir.mkdir(parents=True, exist_ok=True)
    defs = [
        "// AUTO-GENERATED by rtl/gen_graph.py — do not edit.",
        f"// {g.meta}",
        "`ifndef QSX_GRAPH_DEFS_SVH", "`define QSX_GRAPH_DEFS_SVH",
        f"`define QSX_V {V}", f"`define QSX_E {E}", f"`define QSX_VB {vb}", f"`define QSX_EB {eb}",
        f"`define QSX_TB {tb}", f"`define QSX_MD {md}", f"`define QSX_SB {sb}", f"`define QSX_DB {db}",
        "`endif", "",
    ]
    tabs = [
        "// AUTO-GENERATED by rtl/gen_graph.py — do not edit. Included inside modules.",
        f"localparam [{E * vb}-1:0] G_EU = {pack(g.eu, vb)};",
        f"localparam [{E * vb}-1:0] G_EV = {pack(g.ev, vb)};",
        f"localparam [{E}-1:0] G_EBND = {pack([int(v == V) for v in g.ev], 1)};",
        f"localparam [{E}-1:0] G_OBS0 = {pack(obs0, 1)};",
        f"localparam [{E * tb}-1:0] G_THR = {pack(g.thr, tb)};",
        f"localparam [{E * sb}-1:0] G_EU_SLOT = {pack(eu_slot, sb)};",
        f"localparam [{E * sb}-1:0] G_EV_SLOT = {pack(ev_slot, sb)};",
        f"localparam [{V * md}-1:0] G_SLOT_VALID = {pack(slot_valid, 1)};",
        f"localparam [{V * md * eb}-1:0] G_SLOT_E = {pack(slot_e, eb)};",
        f"localparam [{V * md * vb}-1:0] G_SLOT_W = {pack(slot_w, vb)};",
        f"localparam [{V * md * sb}-1:0] G_SLOT_BACK = {pack(slot_back, sb)};",
        f"localparam [{V}-1:0] G_HAS_BEDGE = {pack([int(b >= 0) for b in bedge], 1)};",
        f"localparam [{V * eb}-1:0] G_BEDGE = {pack([max(b, 0) for b in bedge], eb)};",
        "",
    ]
    (outdir / "qsx_graph_defs.svh").write_text("\n".join(defs))
    (outdir / "qsx_graph_tables.svh").write_text("\n".join(tabs))
    return {"V": V, "E": E, "VB": vb, "EB": eb, "TB": tb, "MD": md, "SB": sb, "DB": db}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--graph", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--tb", type=int, default=None, help="threshold bits (default from graph, min 2)")
    a = ap.parse_args()
    info = emit(Graph.read(a.graph), Path(a.out), a.tb)
    print(a.out, info)


if __name__ == "__main__":
    main()
